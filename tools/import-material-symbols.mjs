#!/usr/bin/env node
// Imports Material Symbols (Outlined, 24px) from google/material-design-icons at a pinned
// revision and writes Android vector drawables plus a manifest of source URLs.
//
// Usage: node tools/import-material-symbols.mjs
// The icon list lives in android/ui/design-assets/material-symbols/icons.json.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'android/ui/design-assets/material-symbols');
const drawables = path.join(root, 'android/ui/src/main/res/drawable');
const config = JSON.parse(fs.readFileSync(path.join(assets, 'icons.json'), 'utf8'));

const sourceUrl = ({ name, classic }, filled) =>
  `https://raw.githubusercontent.com/google/material-design-icons/${config.revision}` +
  (classic
    ? `/src/${classic}/${name}/materialiconsoutlined/24px.svg`
    : `/symbols/web/${name}/${config.style}/${name}${filled ? '_fill1' : ''}_24px.svg`);

const resourceName = (name, filled) => `ic_${name}${filled ? '_filled' : ''}`;

// Most symbols use a 960-unit grid shifted up by 960; a few older files and the classic set use 24
// units, and the classic set also has an empty square path to fill out its viewBox.
function parse(svg, name) {
  const paths = [...svg.matchAll(/<path\b[^>]*>/g)]
    .filter(([tag]) => !tag.includes('fill="none"'))
    .map(([tag]) => tag.match(/\sd="([^"]+)"/)[1]);
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (paths.length === 0 || ![undefined, '0 0 24 24', '0 -960 960 960'].includes(viewBox)) {
    throw new Error(`${name}: unexpected SVG layout`);
  }
  return { paths, viewport: viewBox === '0 -960 960 960' ? 960 : 24 };
}

function vector(name, filled, mirrored, classic, { paths, viewport }) {
  const label = `${name}${filled ? ' (filled)' : ''}`;
  const set = classic ? 'Material Icons' : 'Material Symbols';
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${set} Outlined "${label}", Apache-2.0. Generated by tools/import-material-symbols.mjs. -->`,
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    '    android:width="24dp"',
    '    android:height="24dp"',
    ...(mirrored ? ['    android:autoMirrored="true"'] : []),
    `    android:viewportWidth="${viewport}"`,
    `    android:viewportHeight="${viewport}">`,
    `    <group android:translateY="${viewport === 960 ? 960 : 0}">`,
    ...paths.map(
      (data) => `        <path\n            android:fillColor="#FF000000"\n            android:pathData="${data}" />`,
    ),
    '    </group>',
    '</vector>',
    '',
  ].join('\n');
}

const manifest = [];
for (const icon of config.icons) {
  for (const filled of icon.filled ? [false, true] : [false]) {
    const url = sourceUrl(icon, filled);
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
    const svg = await response.text();
    const resource = resourceName(icon.name, filled);
    const target = path.join(drawables, `${resource}.xml`);
    fs.writeFileSync(target, vector(icon.name, filled, icon.mirrored === true, Boolean(icon.classic), parse(svg, icon.name)));
    manifest.push({
      name: icon.name,
      filled,
      url,
      resource: path.relative(root, target),
    });
  }
}

fs.writeFileSync(
  path.join(assets, 'manifest.json'),
  JSON.stringify(
    {
      upstream: 'https://github.com/google/material-design-icons',
      revision: config.revision,
      style: config.style,
      license: 'Apache-2.0',
      files: manifest,
    },
    null,
    2,
  ) + '\n',
);
console.log(`Imported ${manifest.length} Material Symbols drawables.`);
